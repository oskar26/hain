#!/usr/bin/env python3
"""Exports EVERY frame (25 fps) of every Pim motion into one big SVG sheet.
Row = motion, column = frame. Each frame is a nested <svg id="<motion>_f<NNN>"> so an agent can
cut out single frames by id. Output: assets/mascot/v2/pim_all_frames.svg (+ .txt copy).
Source of truth stays pim_motion.json / pim_gen.py — regenerate with: python3 tools/pim_frames_svg.py"""
import os, sys, re
sys.path.insert(0, os.path.dirname(__file__))
import pim_gen as g
FPS, CELL, LABEL, PAD = 25, 96, 150, 4
rows, maxn = [], 0
for m in g.MOTIONS:
    dur = m["duration"]; n = max(int(dur / 1000 * FPS), 2)
    rows.append((m, n)); maxn = max(maxn, n)
W = LABEL + maxn * (CELL + PAD); H = len(rows) * (CELL + PAD + 14) + 40
out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" font-family="sans-serif">',
       f'<!-- Pim v2.1 · all frames · {FPS} fps · frame cell viewBox -12 -18 144 144 · {len(rows)} motions · '
       f'frame k shows t = k*{1000//FPS} ms · ids: <motion>_f<NNN> · generated by tools/pim_frames_svg.py -->',
       f'<rect width="{W}" height="{H}" fill="#FFFFFF"/>']
y = 30
for m, n in rows:
    out.append(f'<g id="motion_{m["name"]}" data-duration-ms="{m["duration"]}" data-frames="{n}" data-loop="{str(m.get("loop", False)).lower()}" data-kind="{m.get("kind","")}">')
    out.append(f'<text x="8" y="{y + CELL/2:.0f}" font-size="13" fill="#333">{m["name"]}</text>'
               f'<text x="8" y="{y + CELL/2 + 16:.0f}" font-size="10" fill="#888">{m["duration"]} ms · {n} f</text>')
    for i in range(n):
        inner = g.render(g.sample(m, i * 1000 / FPS))
        inner = re.sub(r'^<svg xmlns="http://www.w3.org/2000/svg" viewBox="-12 -18 144 144">', '', inner)[:-6]
        x = LABEL + i * (CELL + PAD)
        out.append(f'<svg id="{m["name"]}_f{i:03d}" x="{x}" y="{y}" width="{CELL}" height="{CELL}" viewBox="-12 -18 144 144">{inner}</svg>')
    out.append('</g>'); y += CELL + PAD + 14
out.append('</svg>')
svg = "\n".join(out)
d = os.path.join(os.path.dirname(__file__), "..", "assets", "mascot", "v2")
open(os.path.join(d, "pim_all_frames.svg"), "w").write(svg)
open(os.path.join(d, "pim_all_frames.svg.txt"), "w").write(svg)
print(len(rows), "motions,", sum(n for _, n in rows), "frames,", len(svg), "bytes")
