/**
 * Single source of truth: `assets/mascot/v2/motion/pim_motion.json` → `geometry`
 * (generated by tools/pim_gen.py). Do not hand-tune any number here.
 * viewBox = -12 -18 144 144 → content drawn in a 144-unit box starting at (-12,-18).
 */
object PimGeometry {
    const val VIEW_BOX_X = -12f
    const val VIEW_BOX_Y = -18f
    const val VIEW_BOX_SIZE = 144f

    // svg path data, ported verbatim from pim_motion.json
    const val BODY_PATH = "M60 34 C82 34 92 52 92 76 C92 96 80 106 60 106 C40 106 28 96 28 76 C28 52 38 34 60 34 Z"
    const val STEM_PATH = "M60 42 C60 33 59.5 26 57.5 20.5"
    const val LEAF_PATH = "M57.5 20.5 C54 11 44 7.5 36.5 11.5 C38 20 48 24.5 57.5 20.5 Z"
    const val LEAF_VEIN_PATH = "M56 19.5 C51 16 45 14 40 13"

    val BODY_BOTTOM_CENTRE = Offset(x = 60f, y = 106f)
    val STEM_BASE = Offset(x = 60f, y = 36f)
    val LEAF_TIP = Offset(x = 57.5f, y = 20.5f)
    val EYE_L = Offset(x = 48.5f, y = 71f)
    val EYE_R = Offset(x = 71.5f, y = 71f)
    const val EYE_W = 7f
    const val EYE_H = 14f
    const val STROKE_W = 2.5f

    /** Where the mouth sits (T-089), between and below the eyes. */
    val MOUTH = Offset(x = 60f, y = 85f)

    /** The part of the viewBox Pim fills (T-089): 108 units around him, so a 30 dp Pim looks 30 dp. */
    val FRAME_TOP_LEFT = Offset(x = 6f, y = 3f)
    const val FRAME_SIZE = 108f

    /** Default fx anchor: top-right of the head. fxX/fxY are offsets from here. */
    val FX_ANCHOR = Offset(x = 96f, y = 12f)
}

